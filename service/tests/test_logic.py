def test_edges_on_neighbouring_samples_are_all_found():
    pulses = Capture(1000, ["D0"], bytes([0, 1, 0, 1, 0]))
    expected = [[0, 0], [1, 1], [2, 0], [3, 1], [4, 0]]
    assert edges(pulses)["edges"][0] == expected
    assert edges(read_sr(write_sr(pulses)))["edges"][0] == expected

    busy = Capture(1000, ["D0", "D1"], bytes(i % 4 for i in range(100)))   # D0 changes every sample, D1 every second
    small = edges(busy, max_edges=10)
    assert small["truncated"] and small["end"] == 5
    assert small["edges"] == {0: [[0, 0], [1, 1], [2, 0], [3, 1], [4, 0], [5, 1]], 1: [[0, 0], [2, 1], [4, 0]]}
