def test_edges_for_the_waveform_view():
    c = capture(b"U")
    view = edges(c)
    levels = view["edges"][0]
    assert levels[0] == [0, 1] and levels[1][1] == 0                 # idle high, then the start bit
    assert all(v[1] in (0, 1) for v in levels)
    assert view["edges"][1] == [[0, 1]]                              # an idle channel has no edges
    small = edges(capture(), max_edges=40)
    assert small["truncated"] and small["end"] < len(c.samples) * 100


def test_long_captures_decode_quickly():
    text = BOOT * 40
    c = capture(text, rate=8_000_000)                                # about 25 million samples
    started = time.perf_counter()
    assert decode_uart(c, 0, 115200)["bytes"] == text
    assert time.perf_counter() - started < 3


def test_comparing_with_a_console_log():
    console = "garbage before\r\n" + BOOT.decode() + "ARC7621 # "
    same = compare_text(BOOT.decode(), console)
    assert same["ratio"] > 0.95 and same["first_difference"] is None or same["ratio"] > 0.95
    different = compare_text(BOOT.decode().replace("128 MiB", "256 MiB"), console)
    assert different["first_difference"]["line"] == 2
    assert compare_text("", console)["ratio"] == 0.0


def test_the_virtual_boot_capture_decodes_to_the_vdev_boot_log():
    from pcbv.logic import virtual_boot_capture
    from pcbv.serialmgr import scan_text
    c = virtual_boot_capture()
    text = decode_uart(c, 0, estimate_baud(c, 0))["bytes"].decode()
    assert text.startswith("\r\nU-Boot 2015.07-ARC") or "U-Boot 2015.07-ARC" in text[:40]
    assert {"bootloader", "autoboot", "kernel", "login"} <= set(scan_text(text))


