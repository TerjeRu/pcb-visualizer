import time

import pytest

from pcbv.logic import (Capture, LogicError, compare_text, decode_uart, edges, estimate_baud, parse_rate,
                        read_capture, read_csv, read_sr, uart_waveform, write_sr)

BOOT = b"U-Boot 2015.07-ARC (Mar 14 2019)\r\nDRAM:  128 MiB\r\nHit any key to stop autoboot:  3 \r\n"


def capture(text=BOOT, baud=115200, rate=1_000_000, **kw):
    return Capture(rate, [f"D{i}" for i in range(8)], bytes(uart_waveform(text, baud, rate, **kw)))


@pytest.mark.parametrize("text, rate", [("1 MHz", 1_000_000), ("24MHz", 24_000_000), ("500 kHz", 500_000),
                                        ("8000000", 8_000_000), ("2.5 MHz", 2_500_000)])
def test_sample_rates(text, rate):
    assert parse_rate(text) == rate


def test_uart_decodes_exactly_at_several_speeds_and_rates():
    for baud, rate in [(115200, 1_000_000), (115200, 8_000_000), (9600, 100_000), (57600, 500_000)]:
        result = decode_uart(capture(baud=baud, rate=rate), 0, baud)
        assert result["bytes"] == BOOT, (baud, rate)
        assert result["errors"] == 0


def test_gaps_between_characters_and_glitches_do_not_confuse_it():
    c = capture(gap_bits=3.5)
    samples = bytearray(c.samples)
    samples[100] = 0xFE                              # a one-sample glitch in the idle lead-in
    result = decode_uart(Capture(c.samplerate, c.channels, bytes(samples)), 0, 115200)
    assert result["bytes"] == BOOT


def test_the_wrong_speed_gives_garbage_and_framing_errors():
    result = decode_uart(capture(), 0, 57600)
    assert result["bytes"] != BOOT and result["errors"] > 0


def test_speed_is_estimated_from_the_shortest_pulses():
    assert estimate_baud(capture(), 0) == 115200
    assert estimate_baud(capture(baud=9600, rate=100_000), 0) == 9600
    assert estimate_baud(Capture(1_000_000, ["D0"], b"\xff" * 1000), 0) is None


def test_too_slow_a_sample_rate_is_refused():
    with pytest.raises(LogicError, match="at least 4"):
        decode_uart(capture(rate=1_000_000), 0, 460800)


def test_sigrok_sessions_round_trip():
    c = capture()
    data = write_sr(c)
    back = read_sr(data)
    assert back.samplerate == 1_000_000 and back.channels == c.channels and back.samples == c.samples
    assert read_capture(data, "boot.sr").samples == c.samples


def test_csv_export_is_read_with_its_sample_rate():
    text = "; CSV generated by sigrok-cli\n; Samplerate: 1 MHz\nTime,D0,D1\n0,1,0\n1,0,1\n2,1,1\n"
    c = read_csv(text)
    assert c.samplerate == 1_000_000 and c.channels == ["D0", "D1"]
    assert list(c.samples) == [0b01, 0b10, 0b11]
    with pytest.raises(LogicError, match="sample rate"):
        read_csv("D0\n1\n0\n")
    assert read_csv("D0\n1\n0\n", samplerate=1000).samplerate == 1000


